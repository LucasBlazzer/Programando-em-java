package AlgoritmosLacosRepeticao.Classes;

/**
 * 2 - Contagem Regressiva
 * Crie um programa que imprima os números 10 a 0
 */
public class ContagemRegressiva {
    public static void executarRegressiva(){
        System.out.println("Executando regressiva...");

        for(int i = 10; i >= 0; i--){
            System.out.println(i);
        }
    }
}
