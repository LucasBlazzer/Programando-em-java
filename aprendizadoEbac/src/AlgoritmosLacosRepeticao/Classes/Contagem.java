package AlgoritmosLacosRepeticao.Classes;

/**
 * 1 - Contagem de 1 a 10
 * Crie um algoritmo que conte de 1 a 10
 * Conteúdo praticado:
 * for - contador - incremento
 */
public class Contagem {
    public static void executarContagem(){
        System.out.println("Contagem");

        for(int i = 0; i < 11; i++){
            System.out.println(i);
        }
    }
}
